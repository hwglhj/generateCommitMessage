import javax.swing.JPanel

@RunWith(JUnit38ClassRunner::class)
class QuickModelToolbarGenerationTest : LightPlatformTestCase() {
    fun testToolbarChoiceImmediatelyGeneratesSelectedChangesUsingNewSiteAndModel() {
        Flow().use { flow ->
            val popup = flow.open()
            assertTrue("Opening the menu must not generate", flow.requests.isEmpty())
            val child = flow.site(popup, 1)
            assertTrue("Opening a site must not generate", flow.requests.isEmpty())

            choose(child, "working")
            await("Selecting a toolbar model must generate without clicking lightning") { flow.requests.isNotEmpty() }
            await("Success must close the original root and site menu") { popup.isDisposed && child.isDisposed }

            assertEquals(listOf("/backup/chat/completions" to "working"), flow.requests.toList())
            assertTrue(flow.prompts.single().contains("only-selected-change"))
            assertFalse(flow.prompts.single().contains("not-selected-change"))
            assertEquals("fix: generated by working", flow.message)
            assertEquals("backup", flow.settings.activeApiConfigId)
        }
    }

    fun testToolbarFailureKeepsSamePickerAndSelectingCurrentModelRetries() {
        Flow().use { flow ->
            val popup = flow.open()
            val child = flow.site(popup, 0)
            choose(child, "broken")
            await("The currently selected model must also start generation") { flow.requests.size == 1 }
            await("Failure must restore selection") { !CommitGenerationTask.gate.isRunning && child.list.isEnabled }
            assertFalse(popup.isDisposed)
            assertFalse(child.isDisposed)
            assertEquals("original draft", flow.message)

            choose(child, "broken")
            await("The same failed model can be retried explicitly") { flow.requests.size == 2 }
            await("The second failure must keep the same picker") { !CommitGenerationTask.gate.isRunning && child.list.isEnabled }
            choose(child, "working")
            await("A successful choice must close both menus") { popup.isDisposed && child.isDisposed }
            assertEquals(listOf("broken", "broken", "working"), flow.requests.map { it.second })
        }
    }

    fun testEmptySelectionChangesModelWithoutSendingAnyChanges() {
        Flow().use { flow ->
            flow.selection.clear()
            val popup = flow.open()
            val child = flow.site(popup, 1)
            choose(child, "working")
            UIUtil.dispatchAllInvocationEvents()

            assertEquals("backup", flow.settings.activeApiConfigId)
            assertTrue(flow.requests.isEmpty())
            assertFalse(CommitGenerationTask.gate.isRunning)
            assertEquals("original draft", flow.message)
            assertFalse(popup.isDisposed)

            flow.selection.add(change("selected-after-warning"))
            choose(child, "working")
            await("Selecting changes after the warning allows generation") { popup.isDisposed }
            assertTrue(flow.prompts.single().contains("selected-after-warning"))
        }
    }

    fun testMissingCommitPanelStillAllowsModelSelectionWithoutARequest() {
        Flow().use { flow ->
            val popup = flow.open(includePanel = false)
            choose(flow.site(popup, 1), "working")
            UIUtil.dispatchAllInvocationEvents()

            assertEquals("backup", flow.settings.activeApiConfigId)
            assertTrue(flow.requests.isEmpty())
            assertFalse(CommitGenerationTask.gate.isRunning)
            assertFalse(popup.isDisposed)
        }
    }

    fun testFirstChoiceReadsCurrentSelectionAndProtectsNewlyEditedCommitText() {
        Flow().use { flow ->
            val popup = flow.open()
            flow.selection.clear()
            flow.selection.add(change("chosen-after-opening"))
            flow.afterRequest = { flow.message = "edited while generating" }
            choose(flow.site(popup, 1), "working")
            await("Generation should complete") { popup.isDisposed && flow.requests.isNotEmpty() }

            assertTrue(flow.prompts.single().contains("chosen-after-opening"))
            assertFalse(flow.prompts.single().contains("only-selected-change"))
            assertEquals("edited while generating", flow.message)
        }
    }

    private fun choose(popup: KeepingActionListPopup, model: String) {
        val step = popup.listStep as ActionPopupStep
        popup.list.selectedIndex = step.values.indexOfFirst { it.text == model }.also { assertTrue(it >= 0) }
        popup.handleSelect(true)
    }

    private fun await(message: String, condition: () -> Boolean) {
        val end = System.nanoTime() + 10_000_000_000L
        while (!condition() && System.nanoTime() < end) {
            UIUtil.dispatchAllInvocationEvents()
            Thread.sleep(10)
        }
        UIUtil.dispatchAllInvocationEvents()
        assertTrue(message, condition())
    }

    private fun change(content: String): Change = Change(null, object : ContentRevision {
        override fun getContent(): String = content
        override fun getFile() = VcsUtil.getFilePath("/selected.txt", false)
        override fun getRevisionNumber() = VcsRevisionNumber.NULL
    })

    private inner class Flow : AutoCloseable {
        val settings = AiCommitSettings.getInstance()
        private val savedSettings = settings.generationSnapshot()
        val selection = mutableListOf(change("only-selected-change"))
        val requests = CopyOnWriteArrayList<Pair<String, String>>()
        val prompts = CopyOnWriteArrayList<String>()
        @Volatile var message = "original draft"
        var afterRequest: () -> Unit = {}
        private val server = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0)
        private val popups = mutableListOf<QuickModelActionPopup>()
        private val panel = Proxy.newProxyInstance(
            CheckinProjectPanel::class.java.classLoader, arrayOf(CheckinProjectPanel::class.java),
        ) { _, method, arguments ->
            when (method.name) {
                "getSelectedChanges" -> selection
                "getCommitMessage" -> message
                "setCommitMessage" -> { message = arguments!![0] as String; null }
                "getProject" -> project
                else -> null
            }
        } as CheckinProjectPanel

        init {
            server.createContext("/") { exchange ->
                val json = JsonParser.parseString(exchange.requestBody.bufferedReader().use { it.readText() }).asJsonObject
                val model = json.get("model").asString
                prompts.add(json.getAsJsonArray("messages")[0].asJsonObject.get("content").asString)
                requests.add(exchange.requestURI.path to model)
                afterRequest()
                val body = if (model == "broken") """{"error":{"message":"unavailable"}}"""
                    else """{"choices":[{"message":{"content":"fix: generated by $model"}}]}"""
                val bytes = body.toByteArray(Charsets.UTF_8)
                exchange.sendResponseHeaders(if (model == "broken") 503 else 200, bytes.size.toLong())
                exchange.responseBody.use { it.write(bytes) }
            }
            server.start()
            settings.mode = AiCommitSettings.MODE_API
            settings.includeRecentCommits = false
            settings.apiConfigs = mutableListOf(
                ApiProviderConfig(id = "primary", name = "Primary", apiKey = "test-key", model = "broken",
                    models = mutableListOf("broken", "working"), baseUrl = "http://127.0.0.1:${server.address.port}/primary"),
                ApiProviderConfig(id = "backup", name = "Backup", apiKey = "test-key", model = "working",
                    baseUrl = "http://127.0.0.1:${server.address.port}/backup"),
            )
            settings.activeApiConfigId = "primary"
        }

        fun open(includePanel: Boolean = true): QuickModelActionPopup {
            val action = QuickModelAction()
            val context = SimpleDataContext.builder()
                .setParent(SimpleDataContext.getProjectContext(project))
                .add(VcsDataKeys.COMMIT_MESSAGE_CONTROL, if (includePanel) panel else null)
                // The panel's checked selection must win over unrelated data-context changes.
                .add(VcsDataKeys.CHANGES, arrayOf(change("not-selected-change")))
                .add(PlatformCoreDataKeys.CONTEXT_COMPONENT, JPanel())
                .build()
            val event = AnActionEvent.createFromAnAction(action, null, ActionPlaces.UNKNOWN, context)
            return QuickModelAction.createToolbarPopup(event)!!.also {
                popups.add(it)
                Disposer.register(testRootDisposable, it)
            }
        }

        fun site(root: QuickModelActionPopup, index: Int): KeepingActionListPopup {
            val step = root.listStep as ActionPopupStep
            val site = step.values[index]
            val childStep = step.onChosen(site, false) as ActionPopupStep
            val child = QuickModelActionPopup::class.java.getDeclaredMethod(
                "createPopup", WizardPopup::class.java, PopupStep::class.java, Any::class.java,
            ).apply { isAccessible = true }.invoke(root, root, childStep, site) as KeepingActionListPopup
            WizardPopup::class.java.getDeclaredField("myChild").apply { isAccessible = true }.set(root, child)
            return child
        }

        override fun close() {
            server.stop(0)
            for (popup in popups) if (!popup.isDisposed) Disposer.dispose(popup)
            settings.loadState(savedSettings)
        }
    }
}
