package com.fs.aicommit

import com.google.gson.JsonParser
import com.intellij.openapi.actionSystem.AnActionEvent
import com.intellij.openapi.actionSystem.ActionPlaces
import com.intellij.openapi.application.ModalityState
import com.intellij.openapi.progress.EmptyProgressIndicator
import com.intellij.openapi.progress.ProcessCanceledException
import com.intellij.testFramework.LightPlatformTestCase
import org.junit.internal.runners.JUnit38ClassRunner
import org.junit.runner.RunWith
import javax.swing.JPanel

@RunWith(JUnit38ClassRunner::class)
class CommitGenerationRetryTest : LightPlatformTestCase() {
    fun testChoosingAnotherApiSiteRetriesWithItsModelAndTheOriginalInput() {
        val flow = Flow()
        flow.request.start()
        flow.finishNext()

        assertEquals(1, flow.failures)
        assertEquals(1, flow.pickers.size)
        assertEquals(1, flow.sent.size)
        assertFalse(CommitGenerationTask.gate.isRunning)

        flow.choose(flow.settings.apiConfigs[1].id, "working")

        assertTrue("Selecting the model must queue a new request immediately", CommitGenerationTask.gate.isRunning)
        assertEquals(1, flow.tasks.size)
        flow.finishNext()

        assertEquals(listOf("broken", "working"), flow.sent.map { it.second })
        assertEquals("https://backup.invalid/v1/chat/completions", flow.sent.last().first)
        assertEquals(flow.prompts.first(), flow.prompts.last())
        assertTrue(flow.prompts.last().contains("selected-change"))
        assertEquals(listOf("fix: generated by new model"), flow.results)
        assertEquals(1, flow.pickers.size)
        assertFalse(CommitGenerationTask.gate.isRunning)
    }

    fun testAnotherFailureAllowsAnotherSelectionButNeverRetriesOnItsOwn() {
        val flow = Flow()
        flow.request.start()
        flow.finishNext()
        assertTrue(flow.tasks.isEmpty())

        flow.choose("primary", "also-broken")
        flow.finishNext()
        assertEquals(2, flow.failures)
        assertEquals(2, flow.pickers.size)
        assertTrue(flow.tasks.isEmpty())

        flow.choose("backup", "working")
        flow.finishNext()
        assertEquals(listOf("broken", "also-broken", "working"), flow.sent.map { it.second })
        assertEquals(1, flow.results.size)
    }

    fun testCanceledRetryDoesNotOpenAnotherFailurePicker() {
        val flow = Flow()
        flow.request.start()
        flow.finishNext()
        flow.choose("backup", "working")
        val task = flow.tasks.removeAt(0)
        task.onThrowable(ProcessCanceledException())
        task.onFinished()

        assertEquals(1, flow.cancellations)
        assertEquals(1, flow.pickers.size)
        assertEquals(1, flow.sent.size)
        assertTrue(flow.results.isEmpty())
        assertFalse(CommitGenerationTask.gate.isRunning)
    }

    fun testRepeatedSelectionCannotStartDuplicateRequestsOrChangeInflightModel() {
        val flow = Flow()
        flow.request.start()
        val oldTask = flow.finishNext()
        flow.choose("backup", "working")
        flow.choose("primary", "also-broken")
        oldTask.onFinished()

        assertEquals(1, flow.tasks.size)
        assertTrue(CommitGenerationTask.gate.isRunning)
        assertEquals("backup", flow.settings.activeApiConfigId)
        flow.finishNext()
        assertEquals(listOf("broken", "working"), flow.sent.map { it.second })
    }

    fun testRetryIsSuppressedWhenTheOriginalProjectCanNoLongerBeUpdated() {
        val flow = Flow()
        flow.request.start()
        flow.finishNext()
        flow.open = false
        flow.pickers.last().invoke()

        assertTrue(flow.tasks.isEmpty())
        assertEquals(1, flow.sent.size)
        assertFalse(CommitGenerationTask.gate.isRunning)
    }

    fun testNormalQuickSwitchOnlyChangesSettings() {
        val flow = Flow()
        val choice = QuickModelAction.apiSites(flow.settings)[1].choices.single()
        perform(QuickModelAction.modelToggle(flow.settings, project, choice))

        assertEquals("backup", flow.settings.activeApiConfigId)
        assertTrue(flow.tasks.isEmpty())
        assertTrue(flow.sent.isEmpty())
    }

    fun testCliChoiceRetriesWithFreshModelAndThinkingLevel() {
        val flow = Flow()
        flow.settings.mode = AiCommitSettings.MODE_CLI
        flow.settings.model = "broken high"
        val usedModels = mutableListOf<String>()
        val request = flow.newRequest { snapshot ->
            usedModels.add(snapshot.model)
            if (snapshot.model.startsWith("broken")) throw IllegalStateException("CLI failed")
            "fix: CLI retry"
        }
        request.start()
        flow.finishNext()
        val choice = QuickModelAction.choices(flow.settings, listOf("working")).last()
        perform(QuickModelAction.modelToggle(flow.settings, project, choice, flow.pickers.last()))
        flow.finishNext()

        assertEquals(listOf("broken high", "working high"), usedModels)
        assertEquals(listOf("fix: CLI retry"), flow.results)
    }

    fun testRemovedModelDoesNotRetryOrChangeTheActiveSite() {
        val flow = Flow()
        flow.request.start()
        flow.finishNext()
        val choice = QuickModelAction.apiSites(flow.settings)[1].choices.single()
        val action = QuickModelAction.modelToggle(flow.settings, project, choice, flow.pickers.last())
        flow.settings.apiConfigs.removeAt(1)
        perform(action)

        assertEquals("primary", flow.settings.activeApiConfigId)
        assertTrue(flow.tasks.isEmpty())
        assertEquals(1, flow.sent.size)
    }

    private fun perform(action: com.intellij.openapi.actionSystem.AnAction) {
        action.actionPerformed(AnActionEvent.createFromAnAction(
            action, null, ActionPlaces.POPUP, quickModelPopupDataContext(project, JPanel()),
        ))
    }

    private inner class Flow {
        val settings = AiCommitSettings().apply {
            mode = AiCommitSettings.MODE_API
            includeRecentCommits = false
            apiConfigs = mutableListOf(
                ApiProviderConfig(id = "primary", name = "Primary", apiKey = "test-key",
                    baseUrl = "https://primary.invalid/v1", model = "broken", models = mutableListOf("broken", "also-broken")),
                ApiProviderConfig(id = "backup", name = "Backup", apiKey = "test-key",
                    baseUrl = "https://backup.invalid/v1", model = "working"),
            )
            activeApiConfigId = "primary"
        }
        val tasks = mutableListOf<CommitGenerationTask>()
        val pickers = mutableListOf<() -> Unit>()
        val sent = mutableListOf<Pair<String, String>>()
        val prompts = mutableListOf<String>()
        val results = mutableListOf<String>()
        var failures = 0
        var cancellations = 0
        var open = true
        private val client = ApiClient { http ->
            val body = JsonParser.parseString(http.body).asJsonObject
            val model = body.get("model").asString
            sent.add(http.url to model)
            prompts.add(body.getAsJsonArray("messages")[0].asJsonObject.get("content").asString)
            if (model == "working") ApiHttpResponse(200, """{"choices":[{"message":{"content":"fix: generated by new model"}}]}""")
            else ApiHttpResponse(503, """{"error":{"message":"model unavailable"}}""")
        }
        val request = newRequest { snapshot ->
            AiCommitService(project, snapshot, client).generateFromDiff("+ selected-change")
        }

        fun newRequest(generate: (AiCommitSettings) -> String) = CommitGenerationRequest(
            project = project,
            settings = settings,
            generate = { snapshot, _ -> generate(snapshot) },
            generated = { results.add(it) },
            failed = { failures++ },
            canceled = { cancellations++ },
            showModelSwitcher = { pickers.add(it) },
            canUpdateUi = { open },
            runTask = { task ->
                tasks.add(task)
                com.intellij.openapi.util.Disposer.register(testRootDisposable) { task.onFinished() }
            },
        )

        fun choose(configId: String, model: String) {
            val choice = QuickModelAction.apiSites(settings).first { it.configId == configId }
                .choices.first { it.model == model }
            perform(QuickModelAction.modelToggle(settings, project, choice, pickers.last()))
        }

        fun finishNext(): CommitGenerationTask {
            assertFalse("A generation task must have been queued", tasks.isEmpty())
            val task = tasks.removeAt(0)
            try {
                task.run(EmptyProgressIndicator(ModalityState.NON_MODAL))
                task.onSuccess()
            } catch (error: Exception) {
                task.onThrowable(error)
            } finally {
                task.onFinished()
            }
            return task
        }
    }
}
